-- 배포용 복구: 구매 요청 테이블.
-- 같은 DDL이 db/pending/trade-p2(V2026102103)에만 있어, db/migration만으로 만든 DB에는 테이블이 없다.
-- 이미 pending 경로나 수동 작업으로 만든 DB에서도 실패하지 않도록 모두 존재 여부를 확인한다.

CREATE TABLE IF NOT EXISTS purchase_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    listing_id BIGINT NOT NULL,
    request_status VARCHAR(20) NOT NULL,
    transaction_status VARCHAR(20),
    seller_confirmed_version BIGINT,
    buyer_confirmed_version BIGINT,
    cancelled_by_id BIGINT,
    cancel_reason VARCHAR(500),
    cancelled_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_purchase_requests_room FOREIGN KEY (room_id) REFERENCES chat_rooms (id),
    CONSTRAINT fk_purchase_requests_listing FOREIGN KEY (listing_id) REFERENCES listings (id),
    CONSTRAINT fk_purchase_requests_cancelled_by FOREIGN KEY (cancelled_by_id) REFERENCES users (id),
    CONSTRAINT ck_purchase_requests_request_status
        CHECK (request_status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_purchase_requests_transaction_status
        CHECK (transaction_status IS NULL OR transaction_status IN ('RESERVED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_purchase_requests_status_pair
        CHECK (
            (request_status = 'PENDING' AND transaction_status IS NULL)
            OR (request_status = 'REJECTED' AND transaction_status IS NULL)
            OR (request_status = 'ACCEPTED'
                AND transaction_status IS NOT NULL
                AND transaction_status IN ('RESERVED', 'COMPLETED'))
            OR (request_status = 'CANCELLED' AND (transaction_status IS NULL OR transaction_status = 'CANCELLED'))
        )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_purchase_requests_pending_room
    ON purchase_requests (room_id)
    WHERE request_status = 'PENDING';

CREATE UNIQUE INDEX IF NOT EXISTS uq_purchase_requests_reserved_listing
    ON purchase_requests (listing_id)
    WHERE transaction_status = 'RESERVED';

CREATE INDEX IF NOT EXISTS ix_purchase_requests_listing ON purchase_requests (listing_id);
