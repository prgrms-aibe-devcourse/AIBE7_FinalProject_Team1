CREATE TABLE electronic_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_type VARCHAR(30) NOT NULL,
    manufacturer VARCHAR(100) NOT NULL,
    model_name VARCHAR(150) NOT NULL,
    purchased_at DATE,
    serial_fingerprint VARCHAR(64) NOT NULL,
    serial_last4 VARCHAR(4) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_electronic_products_serial_fingerprint UNIQUE (serial_fingerprint),
    CONSTRAINT ck_electronic_products_product_type CHECK (product_type IN ('LAPTOP')),
    CONSTRAINT ck_electronic_products_serial_last4 CHECK (char_length(serial_last4) BETWEEN 1 AND 4)
);

CREATE TABLE laptop_details (
    product_id BIGINT PRIMARY KEY,
    cpu VARCHAR(100),
    memory_gb INTEGER,
    storage_gb INTEGER,
    storage_type VARCHAR(30),
    gpu VARCHAR(100),
    display_size_inches NUMERIC(4, 1),
    operating_system VARCHAR(50),
    CONSTRAINT fk_laptop_details_product
        FOREIGN KEY (product_id) REFERENCES electronic_products (id),
    CONSTRAINT ck_laptop_details_memory_gb CHECK (memory_gb IS NULL OR memory_gb > 0),
    CONSTRAINT ck_laptop_details_storage_gb CHECK (storage_gb IS NULL OR storage_gb > 0),
    CONSTRAINT ck_laptop_details_display_size CHECK (
        display_size_inches IS NULL OR display_size_inches > 0
    ),
    CONSTRAINT ck_laptop_details_storage_type CHECK (
        storage_type IS NULL OR storage_type IN ('SSD', 'HDD', 'EMMC', 'OTHER')
    )
);
