CREATE TABLE ownership_transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    from_user_id BIGINT NOT NULL,
    to_user_id BIGINT,
    token_hash VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    transfer_type VARCHAR(20) NOT NULL DEFAULT 'DIRECT',
    purchase_request_id BIGINT,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    cancelled_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_transfers_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT fk_transfers_from_user FOREIGN KEY (from_user_id) REFERENCES users (id),
    CONSTRAINT fk_transfers_to_user FOREIGN KEY (to_user_id) REFERENCES users (id),
    CONSTRAINT uk_transfers_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_transfers_status CHECK (status IN ('PENDING', 'COMPLETED', 'CANCELLED', 'EXPIRED'))
);

CREATE INDEX ix_transfers_product_status ON ownership_transfers (product_id, status);
CREATE INDEX ix_transfers_from_user ON ownership_transfers (from_user_id);
