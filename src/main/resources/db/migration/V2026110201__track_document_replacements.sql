-- 증빙 사본을 재마스킹본으로 교체한 기록.
-- 교체해도 문서 번호와 이력 연결은 유지되므로, 확정 뒤에 다른 파일로 바뀐 사실을 나중에 확인할 수 있게 남긴다.
-- 파일 자체는 저장하지 않고 종류·크기·SHA-256만 기록한다. 이전 파일의 SHA-256은 업로드 때 저장하지 않아 알 수 없다.

ALTER TABLE documents ADD COLUMN replacement_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE documents ADD COLUMN last_replaced_at TIMESTAMP WITH TIME ZONE;

CREATE TABLE document_replacements (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id      BIGINT       NOT NULL REFERENCES documents (id),
    from_version     INTEGER      NOT NULL,
    to_version       INTEGER      NOT NULL,
    replaced_by_id   BIGINT       NOT NULL,
    was_protected    BOOLEAN      NOT NULL,
    old_content_type VARCHAR(100) NOT NULL,
    new_content_type VARCHAR(100) NOT NULL,
    old_byte_size    BIGINT       NOT NULL,
    new_byte_size    BIGINT       NOT NULL,
    new_sha256       VARCHAR(64)  NOT NULL,
    replaced_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_document_replacements_version CHECK (to_version > from_version)
);

CREATE INDEX idx_document_replacements_document ON document_replacements (document_id, id);
