-- P2 제품 이력(HIST-01~08) 저장 구조.
-- 일반 이력은 현재 소유자가 작성하고, TRANSFER 이력은 향후 소유권 이전 서비스만 생성한다.

-- 판매 초안 데모 fixture가 먼저 만드는 최소 product_events 테이블도 확장할 수 있게 한다.
CREATE TABLE IF NOT EXISTS product_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL
);

ALTER TABLE product_events ADD COLUMN IF NOT EXISTS author_id BIGINT;
ALTER TABLE product_events ADD COLUMN IF NOT EXISTS event_type VARCHAR(30) NOT NULL DEFAULT 'INSPECTION';
ALTER TABLE product_events ADD COLUMN IF NOT EXISTS occurred_on DATE NOT NULL DEFAULT CURRENT_DATE;
ALTER TABLE product_events ADD COLUMN IF NOT EXISTS title VARCHAR(200) NOT NULL DEFAULT '기존 이력';
ALTER TABLE product_events ADD COLUMN IF NOT EXISTS content VARCHAR(2000);
ALTER TABLE product_events ADD COLUMN IF NOT EXISTS service_provider VARCHAR(200);
ALTER TABLE product_events ADD COLUMN IF NOT EXISTS cost BIGINT;
ALTER TABLE product_events ADD COLUMN IF NOT EXISTS replaced_part VARCHAR(200);
ALTER TABLE product_events ADD COLUMN IF NOT EXISTS specs_before JSONB;
ALTER TABLE product_events ADD COLUMN IF NOT EXISTS specs_after JSONB;
ALTER TABLE product_events ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'VALID';
ALTER TABLE product_events ADD COLUMN IF NOT EXISTS transfer_request_id BIGINT;
ALTER TABLE product_events ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE product_events ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP;

UPDATE product_events pe
SET author_id = (SELECT p.owner_id FROM products p WHERE p.id = pe.product_id)
WHERE pe.event_type <> 'TRANSFER' AND pe.author_id IS NULL;

ALTER TABLE product_events ADD CONSTRAINT fk_product_events_product
    FOREIGN KEY (product_id) REFERENCES products (id);
ALTER TABLE product_events ADD CONSTRAINT ck_product_events_type CHECK (
    event_type IN ('PURCHASE', 'INSPECTION', 'REPAIR', 'PART_REPLACEMENT', 'SPEC_CHANGE', 'TRANSFER')
);
ALTER TABLE product_events ADD CONSTRAINT ck_product_events_status
    CHECK (status IN ('VALID', 'VOID'));
ALTER TABLE product_events ADD CONSTRAINT ck_product_events_cost
    CHECK (cost IS NULL OR cost >= 0);
ALTER TABLE product_events ADD CONSTRAINT ck_product_events_author CHECK (
    (event_type = 'TRANSFER' AND author_id IS NULL AND transfer_request_id IS NOT NULL)
    OR (event_type <> 'TRANSFER' AND author_id IS NOT NULL AND transfer_request_id IS NULL)
);
ALTER TABLE product_events ADD CONSTRAINT ck_product_events_specs CHECK (
    (event_type = 'SPEC_CHANGE' AND specs_before IS NOT NULL AND specs_after IS NOT NULL)
    OR (event_type = 'PART_REPLACEMENT'
        AND ((specs_before IS NULL AND specs_after IS NULL)
            OR (specs_before IS NOT NULL AND specs_after IS NOT NULL)))
    OR (event_type NOT IN ('PART_REPLACEMENT', 'SPEC_CHANGE')
        AND specs_before IS NULL AND specs_after IS NULL)
);
ALTER TABLE product_events ADD CONSTRAINT uk_product_events_transfer UNIQUE (transfer_request_id);

CREATE INDEX IF NOT EXISTS ix_product_events_timeline
    ON product_events (product_id, occurred_on, created_at, id);
CREATE INDEX IF NOT EXISTS ix_product_events_author
    ON product_events (author_id, id);

CREATE TABLE event_documents (
    event_id BIGINT NOT NULL,
    document_id BIGINT NOT NULL,
    PRIMARY KEY (event_id, document_id),
    CONSTRAINT fk_event_documents_event FOREIGN KEY (event_id) REFERENCES product_events (id),
    CONSTRAINT fk_event_documents_document FOREIGN KEY (document_id) REFERENCES documents (id)
);

ALTER TABLE audit_logs ADD COLUMN event_id BIGINT;
ALTER TABLE audit_logs ADD CONSTRAINT fk_audit_logs_event
    FOREIGN KEY (event_id) REFERENCES product_events (id);

ALTER TABLE document_extractions ADD CONSTRAINT fk_extractions_result_event
    FOREIGN KEY (result_event_id) REFERENCES product_events (id);
